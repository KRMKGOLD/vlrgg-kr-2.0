/**
 * AboutLibraries reads POM files through attribute-less detached configurations. Kotlin/Native
 * publications offer both kotlin-api and kotlin-metadata variants there, so pick the API variant.
 */
abstract class PreferKotlinApiUsage : AttributeDisambiguationRule<Usage> {
    override fun execute(details: MultipleCandidatesDetails<Usage>) {
        if (details.consumerValue == null) {
            details.candidateValues.firstOrNull { it.name == "kotlin-api" }?.let(details::closestMatch)
        }
    }
}

dependencies.attributesSchema.attribute(Usage.USAGE_ATTRIBUTE) {
    disambiguationRules.add(PreferKotlinApiUsage::class.java)
}
